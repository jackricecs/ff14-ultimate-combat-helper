#!/usr/bin/env python3
"""
从 cactbot 的 resources/zone_info.ts 生成副本分类表 src/UCH.Core/Data/ZoneTable.g.cs。
cactbot 采用 Apache-2.0 许可；生成文件只包含区域 ID、内容类型与名称等数据。

用法: python3 tools/gen_zone_table.py [cactbot 仓库目录]
      不传目录时自动浅克隆 https://github.com/OverlayPlugin/cactbot（仅 resources/）
每次游戏大/小版本新增副本后运行一次并提交。
"""
import datetime
import os
import re
import subprocess
import sys
import tempfile


def load(cactbot_dir):
    t = open(os.path.join(cactbot_dir, "resources", "zone_info.ts"), encoding="utf-8").read().replace("\r", "")
    for zid, body in re.findall(r"\n  (\d+): \{\n(.*?)\n  \},", t, re.S):
        def g(k):
            m = re.search(r"'%s': '((?:[^'\\]|\\.)*)'" % k, body)
            return m.group(1).replace("\\'", "'") if m else ""
        ct = re.search(r"'contentType': (\d+)", body)
        yield int(zid), int(ct.group(1)) if ct else 0, g("en"), g("cn")


def tier(ct, en):
    # cactbot content_type: 2 Dungeons, 4 Trials, 5 Raids, 28 UltimateRaids, 30 VCDungeonFinder, 37 ChaoticAllianceRaid
    if ct == 28:
        return "Ultimate"
    if ct == 37:
        return "Chaotic"
    if ct == 4:
        if "(Extreme)" in en:
            return "Extreme"
        if "(Unreal)" in en:
            return "Unreal"
        return "Trial"
    if ct == 5:
        return "Savage" if "(Savage)" in en else "Raid"
    if ct == 30:
        return "CriterionSavage" if "(Savage)" in en else "Criterion"
    if ct == 2:
        return "Dungeon"
    return None


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else None
    if not src:
        src = tempfile.mkdtemp()
        subprocess.check_call(["git", "clone", "-q", "--depth", "1", "--filter=blob:none", "--sparse",
                               "https://github.com/OverlayPlugin/cactbot", src])
        subprocess.check_call(["git", "-C", src, "sparse-checkout", "set", "resources"])
    rows = sorted((z, tier(ct, en), en, cn) for z, ct, en, cn in load(src) if tier(ct, en))

    def esc(s):
        return s.replace("\\", "\\\\").replace('"', '\\"')

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "UCH.Core", "Data", "ZoneTable.g.cs")
    with open(out, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write("// <auto-generated>\n")
        f.write("// 由 tools/gen_zone_table.py 从 cactbot resources/zone_info.ts（Apache-2.0）生成，请勿手改。\n")
        f.write("// 生成日期: %s，条目数: %d\n// </auto-generated>\n" % (datetime.date.today().isoformat(), len(rows)))
        f.write("using System.Collections.Generic;\n\nnamespace UltimateCombatHelper.Data\n{\n")
        f.write("    public static partial class ZoneTable\n    {\n")
        f.write("        private static readonly Dictionary<uint, ZoneInfo> Zones = new Dictionary<uint, ZoneInfo>\n        {\n")
        for z, t, en, cn in rows:
            f.write('            { %d, new ZoneInfo(%d, ContentTier.%s, "%s", "%s") },\n' % (z, z, t, esc(en), esc(cn)))
        f.write("        };\n    }\n}\n")
    print("写入 %s（%d 条）" % (os.path.normpath(out), len(rows)))


if __name__ == "__main__":
    main()
